export function getSolareGearIcon(itemId) {
  return itemId ? `/images/solare/gear/${itemId}.webp` : null;
}

export function getSolareGearName(itemId) {
  return SOLARE_GEAR_NAMES[itemId] || (itemId ? `Item ${itemId}` : "");
}

// Combined crystals show up in replays only as set effects (tier 1 = 2-piece, 2 = 4-piece);
// which socket holds them is not recorded.
export function getSolareCrystalSetLabel(set) {
  const fullName = getSolareGearName(set?.crystal_id);
  const shortName = fullName.includes(" - ")
    ? fullName.split(" - ").pop()
    : fullName;
  const tier = Number(set?.tier);
  const pieces = tier >= 2 ? "4-set" : tier === 1 ? "2-set" : null;
  return {
    id: set?.crystal_id,
    icon: getSolareGearIcon(set?.crystal_id),
    name: fullName,
    label: pieces ? `${shortName} · ${pieces}` : shortName,
  };
}

// Turns a 14-entry gear array into the groups rendered by SolareGearPanel.
export function buildSolareGearGroups(gear) {
  if (!Array.isArray(gear) || gear.length === 0) return [];

  const slots = SOLARE_GEAR_SLOTS.map((slot, index) => {
    const entry = Array.isArray(gear[index]) ? gear[index] : [];
    const itemId = Number(entry[0]) || null;
    // Sockets are only rendered when the source actually knows the crystals of this slot.
    const hasCrystalData = entry.length > 1;
    const crystals = Array.from(
      { length: hasCrystalData ? slot.crystals : 0 },
      (_, i) => {
        const crystalId = Number(entry[i + 1]) || null;
        return {
          id: crystalId,
          icon: getSolareGearIcon(crystalId),
          name: crystalId ? getSolareGearName(crystalId) : "Empty socket",
        };
      },
    );
    return {
      ...slot,
      itemId,
      icon: getSolareGearIcon(itemId),
      name: itemId ? getSolareGearName(itemId) : slot.label,
      crystals,
    };
  });

  return SOLARE_GEAR_GROUPS.map((group) => ({
    ...group,
    slots: slots.filter((s) => s.group === group.key),
  }));
}
